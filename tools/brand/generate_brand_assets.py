"""Generate the StreetGym launcher icon and wordmark from one geometry definition.

Outputs (relative to the repository root):
  app/src/main/res/drawable/ic_launcher_foreground.xml   adaptive-icon foreground (also the monochrome layer)
  app/src/main/res/values/ic_launcher_background.xml     adaptive-icon background colour
  app/src/main/res/mipmap-anydpi-v26/ic_launcher.xml     adaptive icon (API 26+)
  app/src/main/res/mipmap-*/ic_launcher.png              legacy icons for API 23-25
  app/src/main/res/drawable/logo.xml                     in-app "STREETGYM" wordmark

Usage:  python tools/brand/generate_brand_assets.py [--play-icon OUT.png] [--preview-svg OUT.svg]

The athlete mark is a front-view figure hanging from a pull-up bar, drawn on the standard
108 x 108 adaptive-icon grid with everything inside the 66 dp safe circle.
"""

from __future__ import annotations

import argparse
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[2]
RES = ROOT / "app" / "src" / "main" / "res"

ORANGE = "#F4511E"
INK = "#1F2933"
WHITE = "#FFFFFF"

# ---------------------------------------------------------------------------
# Athlete mark on the 108-unit adaptive grid (already shifted to optical centre).
# ---------------------------------------------------------------------------
SHIFT_Y = -2.0
BAR = dict(points=[(32, 30), (76, 30)], width=4.5)
LIMBS = [  # polylines drawn with round caps and joins
    dict(points=[(38, 30), (46, 50)], width=6.0),  # left arm
    dict(points=[(70, 30), (62, 50)], width=6.0),  # right arm
    dict(points=[(51.5, 68), (50, 82)], width=6.0),  # left leg
    dict(points=[(56.5, 68), (58, 82)], width=6.0),  # right leg
]
HEAD = dict(center=(54, 42), radius=5.5)
TORSO = dict(points=[(44.5, 49), (63.5, 49), (58.5, 68), (49.5, 68)], soften=3.0)


def _fmt(value: float) -> str:
    text = f"{value:.2f}".rstrip("0").rstrip(".")
    return text if text not in ("-0", "") else "0"


def _poly_path(points, close=False) -> str:
    head, *rest = points
    path = f"M{_fmt(head[0])},{_fmt(head[1])}" + "".join(f" L{_fmt(x)},{_fmt(y)}" for x, y in rest)
    return path + (" Z" if close else "")


def _circle_path(cx: float, cy: float, r: float) -> str:
    return (
        f"M{_fmt(cx)},{_fmt(cy - r)} a{_fmt(r)},{_fmt(r)} 0 1,1 0,{_fmt(2 * r)}"
        f" a{_fmt(r)},{_fmt(r)} 0 1,1 0,{_fmt(-2 * r)} Z"
    )


def mark_vector_paths(color: str) -> list[str]:
    """Android <path> elements for the athlete mark (108-unit grid, unshifted)."""
    stroke = 'android:strokeLineCap="round" android:strokeLineJoin="round"'
    paths = [
        f'<path android:pathData="{_poly_path(BAR["points"])}" android:strokeColor="{color}" '
        f'android:strokeWidth="{_fmt(BAR["width"])}" {stroke} />'
    ]
    for limb in LIMBS:
        paths.append(
            f'<path android:pathData="{_poly_path(limb["points"])}" android:strokeColor="{color}" '
            f'android:strokeWidth="{_fmt(limb["width"])}" {stroke} />'
        )
    paths.append(
        f'<path android:pathData="{_poly_path(TORSO["points"], close=True)}" android:fillColor="{color}" '
        f'android:strokeColor="{color}" android:strokeWidth="{_fmt(TORSO["soften"])}" {stroke} />'
    )
    cx, cy = HEAD["center"]
    paths.append(f'<path android:pathData="{_circle_path(cx, cy, HEAD["radius"])}" android:fillColor="{color}" />')
    return paths


def write_adaptive_icon() -> None:
    body = "\n        ".join(mark_vector_paths(WHITE))
    (RES / "drawable" / "ic_launcher_foreground.xml").write_text(
        f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/brand/generate_brand_assets.py. StreetGym athlete-on-bar mark. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <group android:translateY="{_fmt(SHIFT_Y)}">
        {body}
    </group>
</vector>
""",
        encoding="utf-8",
        newline="\n",
    )
    (RES / "values" / "ic_launcher_background.xml").write_text(
        f"""<?xml version="1.0" encoding="utf-8"?>
<resources>
    <color name="ic_launcher_background">{ORANGE}</color>
</resources>
""",
        encoding="utf-8",
        newline="\n",
    )
    anydpi = RES / "mipmap-anydpi-v26"
    anydpi.mkdir(exist_ok=True)
    (anydpi / "ic_launcher.xml").write_text(
        """<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_foreground" />
</adaptive-icon>
""",
        encoding="utf-8",
        newline="\n",
    )


# ---------------------------------------------------------------------------
# Raster rendering of the mark (legacy mipmaps and the 512 px store icon).
# ---------------------------------------------------------------------------
def _draw_mark(draw: ImageDraw.ImageDraw, to_px, scale: float, color: str) -> None:
    def stroke(points, width):
        pts = [to_px(x, y + SHIFT_Y) for x, y in points]
        w = width * scale
        draw.line(pts, fill=color, width=max(1, round(w)))
        for px, py in pts:
            draw.ellipse([px - w / 2, py - w / 2, px + w / 2, py + w / 2], fill=color)

    stroke(BAR["points"], BAR["width"])
    for limb in LIMBS:
        stroke(limb["points"], limb["width"])
    torso = [to_px(x, y + SHIFT_Y) for x, y in TORSO["points"]]
    draw.polygon(torso, fill=color)
    stroke(TORSO["points"] + TORSO["points"][:1], TORSO["soften"])
    cx, cy = to_px(HEAD["center"][0], HEAD["center"][1] + SHIFT_Y)
    r = HEAD["radius"] * scale
    draw.ellipse([cx - r, cy - r, cx + r, cy + r], fill=color)


def render_icon(size: int, *, legacy: bool) -> Image.Image:
    """legacy=True draws a rounded tile with padding; False is a full-bleed square (store icon)."""
    ss = 8
    big = size * ss
    image = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    draw = ImageDraw.Draw(image)
    if legacy:
        inset = big * 2 / 48
        radius = big * 9 / 48
        draw.rounded_rectangle([inset, inset, big - inset, big - inset], radius=radius, fill=ORANGE)
        tile = big - 2 * inset
        origin = inset
    else:
        draw.rectangle([0, 0, big, big], fill=ORANGE)
        tile = big
        origin = 0.0
    # The visible part of an adaptive icon is the central 72 units (18..90).
    scale = tile / 72.0

    def to_px(x: float, y: float):
        return origin + (x - 18) * scale, origin + (y - 18) * scale

    _draw_mark(draw, to_px, scale, WHITE)
    return image.resize((size, size), Image.LANCZOS)


def write_legacy_icons() -> None:
    for density, size in {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}.items():
        folder = RES / f"mipmap-{density}"
        folder.mkdir(exist_ok=True)
        render_icon(size, legacy=True).save(folder / "ic_launcher.png", optimize=True)


# ---------------------------------------------------------------------------
# Wordmark: rounded monoline capitals, "STREET" in ink and "GYM" in orange.
# ---------------------------------------------------------------------------
LETTERS = {  # (advance width, path) on a 100-unit cap height
    "S": (70, "M66,18 C61,7 51,0 36,0 C19,0 7,9 7,24 C7,40 21,45 36,49 C53,53 67,59 67,76 "
              "C67,91 54,100 35,100 C19,100 8,93 3,81"),
    "T": (64, "M0,0 L64,0 M32,0 L32,100"),
    "R": (62, "M0,100 L0,0 L32,0 C50,0 60,11 60,27 C60,43 50,54 32,54 L0,54 M30,54 L62,100"),
    "E": (56, "M56,0 L0,0 L0,100 L56,100 M0,50 L46,50"),
    "G": (74, "M70,20 C64,7 52,0 39,0 C16,0 0,21 0,50 C0,79 16,100 39,100 C60,100 74,86 74,64 "
              "L74,56 L44,56"),
    "Y": (68, "M0,0 L34,50 L68,0 M34,50 L34,100"),
    "M": (80, "M0,100 L0,0 L40,62 L80,0 L80,100"),
}
LETTER_STROKE = 15.0
TRACKING = 24.0
MARK_SIZE = 130.0
MARK_GAP = 34.0


def wordmark_layout():
    """Returns (viewport_w, viewport_h, mark_box, [(letter, x, color)])."""
    pad = LETTER_STROKE / 2
    top = (MARK_SIZE - 100) / 2  # text cap height is vertically centred on the mark
    x = MARK_SIZE + MARK_GAP + pad
    placed = []
    for index, letter in enumerate("STREETGYM"):
        placed.append((letter, x, INK if index < 6 else ORANGE))
        x += LETTERS[letter][0] + TRACKING
    width = x - TRACKING + pad
    return width, MARK_SIZE, top, placed


def write_wordmark() -> None:
    width, height, top, placed = wordmark_layout()
    scale = MARK_SIZE / 72.0
    mark = "\n            ".join(mark_vector_paths(WHITE))
    letters = []
    for letter, x, color in placed:
        letters.append(
            f"""    <group android:translateX="{_fmt(x)}" android:translateY="{_fmt(top)}">
        <path
            android:pathData="{LETTERS[letter][1]}"
            android:strokeColor="{color}"
            android:strokeWidth="{_fmt(LETTER_STROKE)}"
            android:strokeLineCap="round"
            android:strokeLineJoin="round" />
    </group>"""
        )
    letters_xml = "\n".join(letters)
    (RES / "drawable" / "logo.xml").write_text(
        f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/brand/generate_brand_assets.py. StreetGym wordmark. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{_fmt(width / 2)}dp"
    android:height="{_fmt(height / 2)}dp"
    android:viewportWidth="{_fmt(width)}"
    android:viewportHeight="{_fmt(height)}">
    <path
        android:fillColor="{ORANGE}"
        android:pathData="M28,0 L102,0 A28,28 0 0,1 130,28 L130,102 A28,28 0 0,1 102,130 L28,130 A28,28 0 0,1 0,102 L0,28 A28,28 0 0,1 28,0 Z" />
    <group
        android:scaleX="{_fmt(scale)}"
        android:scaleY="{_fmt(scale)}"
        android:translateX="{_fmt(-18 * scale)}"
        android:translateY="{_fmt(-18 * scale)}">
        <group android:translateY="{_fmt(SHIFT_Y)}">
            {mark}
        </group>
    </group>
{letters_xml}
</vector>
""",
        encoding="utf-8",
        newline="\n",
    )


def write_preview_svg(out: Path) -> None:
    """SVG twin of the wordmark for quick visual review in a browser."""
    width, height, top, placed = wordmark_layout()
    scale = MARK_SIZE / 72.0
    mark = []
    for item in [BAR, *LIMBS]:
        mark.append(f'<path d="{_poly_path(item["points"])}" stroke="{WHITE}" stroke-width="{item["width"]}" '
                    'stroke-linecap="round" stroke-linejoin="round" fill="none"/>')
    mark.append(f'<path d="{_poly_path(TORSO["points"], True)}" fill="{WHITE}" stroke="{WHITE}" '
                f'stroke-width="{TORSO["soften"]}" stroke-linejoin="round"/>')
    mark.append(f'<circle cx="{HEAD["center"][0]}" cy="{HEAD["center"][1]}" r="{HEAD["radius"]}" fill="{WHITE}"/>')
    letters = "".join(
        f'<path transform="translate({_fmt(x)},{_fmt(top)})" d="{LETTERS[l][1]}" stroke="{c}" '
        f'stroke-width="{LETTER_STROKE}" stroke-linecap="round" stroke-linejoin="round" fill="none"/>'
        for l, x, c in placed
    )
    out.write_text(
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {_fmt(width)} {_fmt(height)}" '
        f'width="{_fmt(width)}" height="{_fmt(height)}">'
        f'<rect width="130" height="130" rx="28" fill="{ORANGE}"/>'
        f'<g transform="scale({_fmt(scale)}) translate(-18,-18) translate(0,{SHIFT_Y})">{"".join(mark)}</g>'
        f"{letters}</svg>",
        encoding="utf-8",
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--play-icon", type=Path, help="also write a 512 x 512 full-bleed store icon PNG here")
    parser.add_argument("--preview-svg", type=Path, help="also write an SVG preview of the wordmark here")
    args = parser.parse_args()
    write_adaptive_icon()
    write_legacy_icons()
    write_wordmark()
    if args.play_icon:
        render_icon(512, legacy=False).save(args.play_icon, optimize=True)
    if args.preview_svg:
        write_preview_svg(args.preview_svg)


if __name__ == "__main__":
    main()
